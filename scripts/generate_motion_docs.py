"""Generate docs/MOTION_CATALOG.md from remotion-composer/src/lib/motion-catalog.json.

    python scripts/generate_motion_docs.py

The JSON file is the source of truth for camera moves, transitions and fx ids;
edit it (and the TypeScript that implements them), then re-run this script.
"""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "remotion-composer" / "src" / "lib" / "motion-catalog.json"
OUT = ROOT / "docs" / "MOTION_CATALOG.md"

TEXT_MODES = [
    ("typewriter", "Letters appear one by one."), ("word_pop", "Words pop in with a spring."), ("letter_cascade", "Letters rise in sequence."),
    ("slide_up", "Words slide up into place."), ("blur_in", "Words resolve from a blur."), ("scale_reveal", "Words settle from an oversized scale."),
    ("glitch_in", "Letters jitter in with an accent flash."), ("wave", "Letters ride a travelling wave."), ("mask_wipe", "Line revealed by a left-to-right wipe."),
    ("bounce_in", "Words drop in and bounce."), ("tracking_in", "Letter-spacing tightens as it appears."), ("fade_words", "Words fade in one after another."),
]
SCENES = [
    ("text_card / stat_card / hero_title / callout / comparison / charts / kpi_grid / progress_bar", "Existing component scenes. Any of them accepts `backgroundImage`/`backgroundVideo`, `camera` and `fx`."),
    ("kinetic_text", "Animated typography: `text`, `textMode`, `highlight[]`, `uppercase`."),
    ("split_screen", "`panels[]` (each with `src`, `camera`, `fx`, `label`) and `layout`: 2h, 2v, 3h, 3v, 4, pip, 1+2."),
    ("collage", "`items[]` of free-positioned tiles (`x,y,w,h,rotate,delay,camera,label`) that pop in."),
    ("double_exposure", "`source` + `imageB` blended (screen) with its own fade."),
    ("(image or video source)", "A bare `source` renders through the Stage with `camera`/`fx` (default: slow zoom-in)."),
]
OVERLAYS = [
    ("section_title / stat_reveal / hero_title / provider_chip", "Existing overlays."),
    ("focus_ring", "Animated ring/square around a point: `x`,`y` (percent), `radius`, `text`, `side`, `shape`."),
    ("arrow", "Bobbing arrow pointing at `x`,`y` from `angle`, optional `text`."),
    ("lower_third", "Name/caption bar sliding in: `text`, `subtitle`."),
    ("hud_frame", "Corner brackets, crosshair, REC dot and timecode."),
]


def main() -> None:
    c = json.loads(CATALOG.read_text(encoding="utf-8"))
    lines: list[str] = []
    w = lines.append
    w("# Motion, camera and effects catalog")
    w("")
    w("> Generated by `scripts/generate_motion_docs.py` from `remotion-composer/src/lib/motion-catalog.json`. Do not edit by hand.")
    w("")
    w(c["notes"])
    w("")
    w("Vocabulary draws on: " + ", ".join(c["sources"]) + ". Move names follow common cinematography terms; every move has its own implementation and AI-video prompt written for this project.")
    w("")
    cams = c["camera"]
    w(f"**{len(cams)} camera moves · {len(c['transitions'])} transitions · {len(c['fx'])} effects · {len(TEXT_MODES)} text modes**")
    w("")
    w("## How to use it")
    w("")
    w("```json")
    w(json.dumps({
        "autoCamera": True, "defaultTransition": "dissolve", "fx": [{"type": "film_grain", "intensity": 0.25}, "vignette"],
        "cuts": [{"id": "c1", "source": "img.jpg", "type": "stat_card", "stat": "1,3 s", "subtitle": "LUNA", "backgroundImage": "img.jpg",
                  "camera": {"move": "dolly_in", "origin": {"x": 61, "y": 52}, "intensity": 1.0}, "fx": ["halation", "grade_teal_orange"], "transition_out": "whip_pan_right",
                  "in_seconds": 0, "out_seconds": 5}],
        "overlays": [{"type": "focus_ring", "in_seconds": 1, "out_seconds": 4, "x": 66, "y": 48, "radius": 150, "text": "La Luna"}],
    }, indent=2, ensure_ascii=False))
    w("```")
    w("")
    w("- `camera`: a move id/alias, or a custom spec `{move, intensity, origin:{x,y}, from, to, ease, parallax, shake, delay, hold, reverse, freezeAt}` (state: `s` scale, `x`/`y` percent, `r` degrees, `b` blur px).")
    w("- `origin` is the point (percent of the frame) the camera zooms toward — use it to *point at* an object.")
    w("- `fx`: strings or `{type, ...params}`; the top-level `fx` applies to every scene.")
    w("- Transitions: `transition_out` of a cut (or `transition_in` of the next), duration `transition_duration` seconds (default 0.4).")
    w("")
    w("## Camera moves")
    by = defaultdict(list)
    for m in cams:
        by[m["category"]].append(m)
    for cat, items in by.items():
        w("")
        w(f"### {cat}")
        w("")
        w("| id | aliases | what it does |")
        w("|---|---|---|")
        for m in items:
            w(f"| `{m['id']}` | {', '.join('`'+a+'`' for a in m['aliases']) or '—'} | {m['summary']} |")
    w("")
    w("## Easing")
    w("")
    w(", ".join(f"`{e}`" for e in c["ease"]))
    w("")
    w("## Transitions")
    w("")
    w("| id | what it does |")
    w("|---|---|")
    for t in c["transitions"]:
        w(f"| `{t['id']}` | {t['summary']} |")
    w("")
    w("## Effects (`fx`)")
    fby = defaultdict(list)
    for f in c["fx"]:
        fby[f["category"]].append(f)
    for cat, items in fby.items():
        w("")
        w(f"### {cat}")
        w("")
        w("| id | what it does |")
        w("|---|---|")
        for f in items:
            w(f"| `{f['id']}` | {f['summary']} |")
    w("")
    w("## Text modes (`kinetic_text.textMode`)")
    w("")
    w("| mode | what it does |")
    w("|---|---|")
    for m, s in TEXT_MODES:
        w(f"| `{m}` | {s} |")
    w("")
    w("## Scene types")
    w("")
    w("| type | notes |")
    w("|---|---|")
    for t, s in SCENES:
        w(f"| {t} | {s} |")
    w("")
    w("## Overlay types")
    w("")
    w("| type | notes |")
    w("|---|---|")
    for t, s in OVERLAYS:
        w(f"| {t} | {s} |")
    w("")
    w("## AI-video prompts (for providers that generate real camera motion)")
    w("")
    w("Real 3D moves (orbits, pass-through, fly-through, tracking a subject) are only approximated by the 2D engine. When a video-generation provider is configured, use the move's prompt, which follows a four-part structure: Movement · Speed · Framing · End.")
    w("")
    for m in cams:
        w(f"- **{m['id']}** — {m['ai_prompt']}")
    w("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
